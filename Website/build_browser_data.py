"""Package local site data as a script that also works from file:// URLs."""

import json
from pathlib import Path


def build_browser_data():
    data = Path(__file__).resolve().parent / "data"
    paths = {"catalogue": data / "variables.json", "land": data / "land.geojson"}
    if (data / "world.json").is_file():
        paths["world"] = data / "world.json"
    assets = {key: json.loads(path.read_text(encoding="utf-8")) for key, path in paths.items()}
    script = "// Generated by Website/build_browser_data.py. Edit the source JSON instead.\n"
    script += "globalThis.ByteMeData = {\n"
    for key, value in assets.items():
        script += f"  {key}: {json.dumps(value, ensure_ascii=True, separators=(',', ':'))},\n"
    script += "};\n"
    (data / "browser-data.js").write_text(script, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    build_browser_data()
